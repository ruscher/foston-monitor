#!/bin/sh
# Regenerate firmware/buildroot/patches/linux/0001-bigfoston-mt3351.patch from
# overlay/ + apply-overlay.sh against a pristine Linux tree.
# Usage: mkpatch.sh PRISTINE_LINUX_TREE
# SPDX-License-Identifier: GPL-2.0-only
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$(cd "$1" && pwd)
OUT="$HERE/../buildroot/patches/linux/0001-bigfoston-mt3351.patch"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
GLUE="arch/arm/Kconfig arch/arm/Makefile drivers/irqchip/Kconfig drivers/irqchip/Makefile
drivers/clocksource/Kconfig drivers/clocksource/Makefile drivers/video/fbdev/Makefile
arch/arm/boot/dts/mediatek/Makefile drivers/usb/musb/Kconfig drivers/usb/musb/Makefile
drivers/input/touchscreen/Kconfig drivers/input/touchscreen/Makefile
drivers/mmc/host/Kconfig drivers/mmc/host/Makefile
drivers/video/backlight/Kconfig drivers/video/backlight/Makefile
drivers/power/reset/Kconfig drivers/power/reset/Makefile
sound/arm/Kconfig sound/arm/Makefile
drivers/tty/serial/8250/Kconfig drivers/tty/serial/8250/Makefile"
for f in $GLUE; do
    mkdir -p "$TMP/a/$(dirname "$f")" "$TMP/b/$(dirname "$f")"
    cp "$SRC/$f" "$TMP/a/$f"
    cp "$SRC/$f" "$TMP/b/$f"
done
"$HERE/apply-overlay.sh" "$TMP/b" >/dev/null
( cd "$TMP" && diff -Nur a b ) | sed -E "s/^(\+\+\+|---) ([^\t]*)\t.*/\1 \2/" > "$OUT.tmp" || true
{
    echo "From: BigFoston OS <bigfoston@biglinux>"
    echo "Subject: [PATCH] ARM: MediaTek MT3351 (FOSTON FS-707DC) bring-up"
    echo
    echo "CIRQ interrupt controller, GPT timer, framebuffer boot console and the"
    echo "FS-707DC device tree, all from registers measured on the device."
    echo "Generated by firmware/kernel/mkpatch.sh from firmware/kernel/overlay."
    echo
    cat "$OUT.tmp"
} > "$OUT"
rm -f "$OUT.tmp"
echo "$OUT: $(grep -c '^+++ ' "$OUT") files"
